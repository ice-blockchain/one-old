// src/gen/emit/copilot-agents.ts
// Emit agents/<role>.agent.md for GitHub Copilot plugin discovery (CLI + VS Code).

import { generatedAgents } from './agents';

import type { GenRun } from '../lib/run';

const CLAUDE_TO_COPILOT_TOOLS: Readonly<Record<string, string>> = {
  Read: 'view',
  Grep: 'search',
  Glob: 'search',
  Write: 'edit',
  Edit: 'edit',
  Bash: 'bash',
  Task: 'agent',
  Agent: 'agent',
};

function mapToolsLine(body: string): string {
  return body.replace(/^tools:\s*(?:\[(.*)\]|(.*))\s*$/m, (_match, bracketed: string | undefined, plain: string | undefined) => {
    const inner = bracketed ?? plain ?? '';
    const mapped = inner
      .split(',')
      .map((part: string) => part.trim().replace(/^["']|["']$/g, ''))
      .filter(Boolean)
      .map((tool: string) => CLAUDE_TO_COPILOT_TOOLS[tool] ?? tool.toLowerCase())
      .filter((tool, index, arr) => arr.indexOf(tool) === index);
    return `tools: [${mapped.map((t) => `"${t}"`).join(', ')}]`;
  });
}

function toAgentMd(content: string): string {
  const marker = '<!-- GENERATED BY traffic-one — Copilot agent; do not hand-edit. -->\n';
  if (!content.startsWith('---')) return `${marker}${content}`;
  const end = content.indexOf('---', 3);
  if (end === -1) return `${marker}${content}`;
  const frontmatter = mapToolsLine(content.slice(0, end + 3));
  const body = content.slice(end + 3).replace(/^\n+/, '');
  return `${frontmatter}\n\n${marker}${body}`;
}

function agentRelPath(roleMdRel: string): string {
  const base = roleMdRel.replace(/^agents\//, '').replace(/\.md$/, '');
  return `agents/${base}.agent.md`;
}

export function emitCopilotAgents(run: GenRun): void {
  for (const doc of generatedAgents(run.sourceRoot)) {
    run.file(agentRelPath(doc.relPath), toAgentMd(doc.content));
  }
}
