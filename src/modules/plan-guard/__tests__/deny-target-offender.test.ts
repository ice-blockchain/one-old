// src/modules/plan-guard/__tests__/deny-target-offender.test.ts
// The plan-write aggregator's `denyTarget` must name a target that actually
// OFFENDED. It used to be `filePath` — the direct target, else
// `gateTargets[0]`, the patch's FIRST operation — so on a multi-file
// apply_patch the refusal's machine-readable subject was whichever file the
// agent happened to write first, which had usually violated nothing.
//
// Two readers depend on that subject and neither can recover it from anywhere
// else:
//   * `runs/<id>/debug/decisions.jsonl`, stamped by core/pipeline.ts, where
//     `denyTarget` is the only field naming WHICH file was refused; and
//   * the deny-repeat counter, which signs a refusal as `denyTarget` plus the
//     whole rendered reason (shared/state/deny-repeat.ts), so the subject
//     decides how refusals PARTITION into escalation buckets.
//
// Measured on the fixture below before the fix: a 3-operation patch whose first
// operation stayed constant while the agent cleared the offending files one at
// a time produced three refusals with an identical, path-free reason and an
// identical first operation. All three collapsed into ONE bucket and the third
// escalated — DENY_REPEAT_ESCALATE_AT is 3 — telling an agent that had just
// removed two of three violations to STOP RETRYING, about a file it had already
// fixed. That is the exact false positive deny-repeat.ts's header calls "worse
// than never firing it at all".

