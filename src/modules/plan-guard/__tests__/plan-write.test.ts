// Split into a fixture + two wrappers so the async wrapper below can AWAIT its
// body before the teardown runs: `try { fn(dir) } finally { rm(dir) }` deletes
// the project while a promise-returning body is still using it, which is a
// leaked temp dir and a flaky test in one. Every sync caller is unchanged.
function materializedFixture(stateExtra: Record<string, unknown>): { dir: string; cleanup: () => void } {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 't1-planwrite-'));
  const env = process.env;
  const prev = env.TRAFFIC_ONE_PROJECT_PREFS_PATH;
  const prevPlan = env.TRAFFIC_ONE_USER_PLAN;
  env.TRAFFIC_ONE_PROJECT_PREFS_PATH = path.join(dir, 'prefs.json');
  env.TRAFFIC_ONE_USER_PLAN = 'pro';
  const { team: teamExtra, performance: performanceExtra, ...sharedExtra } = stateExtra;
  const t1 = path.join(dir, '.traffic-one');
  fs.mkdirSync(path.join(t1, 'rules', 'common'), { recursive: true });
  fs.mkdirSync(path.join(t1, 'skills', 'project-memory'), { recursive: true });
  fs.writeFileSync(path.join(t1, 'rules', 'common', 'auth-gate.md'), 'r', 'utf8');
  fs.writeFileSync(path.join(t1, 'skills', 'project-memory', 'SKILL.md'), 's', 'utf8');
  fs.writeFileSync(path.join(t1, 'manifest.json'), JSON.stringify({
    generatedBy: 'traffic-one', stack: 'default', rules: ['rules/common/auth-gate.md'], skills: ['project-memory'],
  }), 'utf8');
  fs.writeFileSync(path.join(dir, 'AGENTS.md'), 'x\n<!-- GENERATED BY traffic-one: project-local active rules -->\n', 'utf8');
  fs.writeFileSync(path.join(dir, 'CLAUDE.md'), 'see agents', 'utf8');
  fs.writeFileSync(path.join(t1, 'plan.md'), 'plan', 'utf8');
  fs.writeFileSync(path.join(t1, '.one.json'), JSON.stringify({
    mode: 'new-project', stack: 'default', frontend: 'react-vite', backend: 'supabase', mobile: { framework: 'none' },
    onboardingComplete: true, materializedStack: 'default|react-vite|supabase|none', ...sharedExtra,
  }), 'utf8');
  if (teamExtra || performanceExtra) {
    const team = teamExtra && typeof teamExtra === 'object'
      ? teamExtra as Record<string, unknown>
      : { mode: 'main-agent', source: 'prompted' };
    const performance = performanceExtra && typeof performanceExtra === 'object'
      ? performanceExtra as Record<string, unknown>
      : { level: team.mode === 'subagents' ? 'high' : 'low', source: 'prompted' };
    fs.writeFileSync(env.TRAFFIC_ONE_PROJECT_PREFS_PATH, JSON.stringify(
      hostScopedPerformancePrefs(performance, team, 'pro'),
    ), 'utf8');
  }
  return {
    dir,
    cleanup: () => {
      if (prev === undefined) delete env.TRAFFIC_ONE_PROJECT_PREFS_PATH; else env.TRAFFIC_ONE_PROJECT_PREFS_PATH = prev;
      if (prevPlan === undefined) delete env.TRAFFIC_ONE_USER_PLAN; else env.TRAFFIC_ONE_USER_PLAN = prevPlan;
      fs.rmSync(dir, { recursive: true, force: true });
    },
  };
}

function withMaterialized(stateExtra: Record<string, unknown>, fn: (cwd: string) => void): void {
  const fixture = materializedFixture(stateExtra);
  try {
    fn(fixture.dir);
  } finally {
    fixture.cleanup();
  }
}

async function withMaterializedAsync(
  stateExtra: Record<string, unknown>,
  fn: (cwd: string) => Promise<void>,
): Promise<void> {
  const fixture = materializedFixture(stateExtra);
  try {
    await fn(fixture.dir);
  } finally {
    fixture.cleanup();
  }
}

function writeCtx(
  cwd: string,
  rawName: string,
  cls: ToolClass,
  toolInput: Record<string, unknown>,
  rawExtra: Record<string, unknown> = {},
  host: HostId = 'claude',
): Ctx {
  const input: HookInput = {
    event: 'PreToolUse', host, cwd,
    raw: { ...rawExtra, tool_name: rawName, tool_input: toolInput },
    tool: { class: cls, rawName },
  };
  return { input, host, cwd, now: () => 'x' } as unknown as Ctx;
}

