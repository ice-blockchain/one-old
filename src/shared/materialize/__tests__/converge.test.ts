// ── the plan migration's return value, and who reads it ───────────────────────
//
// Both call sites here used to DISCARD it, while plan-migration.ts reasoned at
// length in a docblock about which paths `migrated` may name. Nothing read the
// answer, so the reasoning defended nothing. It reaches the agent now, through the
// `context` of whatever outcome convergence returns.

test('materializeProjectFromState: a fold is REPORTED in the outcome the agent reads', () => {
  // A REFUSED materialization, because the report must not depend on the run
  // having succeeded: an unverified plugin root is the cheapest complete-state
  // fixture, and the migration runs before the writer either way.
  withTempProject((dir) => {
    writeCompleteMaterializedFixture(dir);
    fs.writeFileSync(path.join(dir, 'architecture.md'), '# Legacy\n\nModule map from the old file.\n', 'utf8');

    const out = materializeProjectFromState(dir, { trigger: 'unit' });

    assert.match(out.context, /Legacy `architecture\.md` folded into `\.traffic-one\/plan\.md` and removed: `architecture\.md`\./);
    assert.equal(fs.existsSync(path.join(dir, 'architecture.md')), false);
    assert.ok(fs.readFileSync(path.join(dir, '.traffic-one', 'plan.md'), 'utf8').includes('Module map from the old file.'));
  });
});

test('materializeProjectFromState: a document deliberately LEFT ALONE is reported with its reason', () => {
  // The silence this replaces is the one KNOWN-ISSUES item 10 records: a document
  // that is not folded looks identical to one nobody tried to fold. A vendored file
  // carrying delegate markers is the case where the difference matters most.
  withTempProject((dir) => {
    writeCompleteMaterializedFixture(dir);
    const doc = path.join(dir, 'packages', 'vendor', 'architecture.md');
    fs.mkdirSync(path.dirname(doc), { recursive: true });
    fs.writeFileSync(doc, '# Vendor\n\n<!-- opencode-delegate:start -->\n- role: qa-engineer | files: ** | task: pass\n<!-- opencode-delegate:end -->\n', 'utf8');

    const out = materializeProjectFromState(dir, { trigger: 'unit' });

    assert.match(out.context, /Left exactly where it is, unfolded and not removed: `packages\/vendor\/architecture\.md` \(carries Traffic One runtime marker grammar/);
    assert.equal(fs.existsSync(doc), true);
  });
});

test('materializeProjectIfNeeded: the notice survives the paths that return an outcome of their own', () => {
  // `materializeProjectIfNeeded` has to migrate BEFORE its own branches — three of
  // them return `null` and the plan gate still needs the plan — so its notice is
  // threaded into the delegate rather than recomputed there. Recomputing would
  // report nothing: the second, idempotent migration finds the document gone.
  withTempProject((dir) => {
    writeState(dir, { mode: 'existing-codebase', stack: 'not-a-stack', onboardingComplete: true });
    fs.writeFileSync(path.join(dir, 'architecture.md'), '# Legacy\n\nCarried through the delegate.\n', 'utf8');

    const out = materializeProjectIfNeeded(dir, { trigger: 'unit' });

    assert.notEqual(out, null, 'an unknown stack with onboardingComplete delegates rather than going quiet');
    assert.match(out!.context, /folded into `\.traffic-one\/plan\.md` and removed: `architecture\.md`\./);
    assert.ok(fs.readFileSync(path.join(dir, '.traffic-one', 'plan.md'), 'utf8').includes('Carried through the delegate.'));
  });
});
