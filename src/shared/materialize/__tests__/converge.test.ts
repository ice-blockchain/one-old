const declaredContent = (dir: string): ProjectContent => declaredProjectContent(dir, { ...MATERIALIZED_STATE });

// manifest + every declared rule/skill on disk, AGENTS.md with the generated
// marker, and a .one.json whose materializedStack matches the fingerprint so
// isMaterialized() + hasMaterializedProjectAssets() are true.
function writeMaterialized(dir: string): void {
  writeMaterializedContent(dir, { state: { ...MATERIALIZED_STATE } });
  fs.writeFileSync(path.join(dir, 'AGENTS.md'), 'ctx\n<!-- GENERATED BY traffic-one: project-local active rules -->\n', 'utf8');
  fs.writeFileSync(path.join(dir, 'CLAUDE.md'), 'see agents', 'utf8');
  // The ACTIVE HOST'S ROLE CONTRACTS, which "materialized" now includes: a
  // project whose host contract directory is empty is one convergence short, and
  // `materializeProjectIfNeeded` says so (`roleContractsNeedConvergence`). The
  // host is pinned to codex above, so this is `.traffic-one/agents/**`.
  //
  // Deliberately WITHOUT the generated marker: an unmarked file is user-authored
  // as far as every writer is concerned, so it is never swept and never rewritten,
  // and the `written`/`removed` counts other tests in this file assert are
  // untouched by its presence.
  const agents = path.join(dir, '.traffic-one', 'agents');
  fs.mkdirSync(agents, { recursive: true });
  fs.writeFileSync(path.join(agents, 'senior-architect.md'), '# senior-architect\ncontract\n', 'utf8');
  writeState(dir, { ...MATERIALIZED_STATE });
}

