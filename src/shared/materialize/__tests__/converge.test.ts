// Every way materializeProjectAssets can refuse, surfaced end-to-end. The stamp
// assertions are the point: materializedStack/materializedAt/materializedVersion
// are what isMaterialized() reads to short-circuit later convergence, so
// stamping them after a run that materialized nothing is what turned a transient
// condition (a plugin root mid-write, misconfigured, or a checkout) into a
// project that never tried again and silently had zero skills forever.
const REFUSALS = [
  {
    name: "'unverified' root: an unrelated directory",
    skipped: 'plugin-root-unverified',
    expect: ['carries neither a compiled runtime', 'scripts/hook-runtime.cjs'],
    build: (dir: string) => { fs.writeFileSync(path.join(dir, 'README.txt'), 'not a plugin\n', 'utf8'); },
  },
  {
    name: "'source' root: the Traffic One authoring checkout (the reported incident)",
    skipped: 'plugin-root-source-checkout',
    expect: ['SOURCE checkout', 'npm run gen', 'src/modules/skills/skills-catalog/**'],
    build: (dir: string) => {
      fs.mkdirSync(path.join(dir, 'src', 'gen', 'static'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'src', 'gen', 'static', 'plugin-instructions.md'), '# stub\n', 'utf8');
      fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({ name: 'traffic-one' }), 'utf8');
    },
  },
  {
    name: "'installed' root that resolves no rule and no skill (a partial install)",
    skipped: 'resolved-content-empty',
    // The wording is the assertion: this id also covers "45 rules resolved, no
    // skills", so the sentence has to be read off the counts rather than hedged
    // into "0 rule file(s) and 0 skill(s)" — which described none of the three
    // shapes it was serving.
    expect: ['resolved nothing at all — not one rule file, not one skill', 'rsync'],
    build: (dir: string) => {
      fs.mkdirSync(path.join(dir, 'scripts'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'scripts', 'hook-runtime.cjs'), '// stub\n', 'utf8');
      fs.mkdirSync(path.join(dir, 'rules'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'rules', 'unrelated.md'), '# not a Traffic One rule\n', 'utf8');
    },
  },
  {
    // The torn root: a complete `rules/` beside a `skills-catalog/` that lost the
    // race with an rsync. Nothing is empty, so no count-based clause fires — and
    // before the completeness refusal this run swept every manifest-tracked skill
    // and stamped the project materialized over one skill.
    name: "'installed' root with a complete rules/ and a torn skills-catalog/",
    skipped: 'plugin-root-content-incomplete',
    expect: ['content trees are incomplete', 'resolved SOME of this project', 'did not come from one build', 'rsync'],
    build: (dir: string) => {
      const modules = path.resolve(__dirname, '..', '..', '..', 'modules');
      fs.mkdirSync(path.join(dir, 'scripts'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'scripts', 'hook-runtime.cjs'), '// stub\n', 'utf8');
      fs.symlinkSync(path.join(modules, 'rules', 'rules'), path.join(dir, 'rules'), 'dir');
      const kept = path.join(dir, 'skills-catalog', 'project-memory');
      fs.mkdirSync(kept, { recursive: true });
      fs.copyFileSync(
        path.join(modules, 'skills', 'skills-catalog', 'project-memory', 'SKILL.md'),
        path.join(kept, 'SKILL.md'),
      );
    },
  },
] as const;

test("materializeProjectFromState: every plugin-root refusal reports 'skipped', preserves disk byte-for-byte, and never stamps the state", () => {
  for (const refusal of REFUSALS) {
    withTempProject((dir) => {
      const statePath = writeCompleteMaterializedFixture(dir);
      const rulePath = path.join(dir, '.traffic-one', 'rules', 'common', 'auth-gate.md');
      const skillPath = path.join(dir, '.traffic-one', 'skills', 'project-memory', 'SKILL.md');
      const manifestPath = path.join(dir, '.traffic-one', 'manifest.json');
      const before = {
        rule: fs.readFileSync(rulePath, 'utf8'),
        skill: fs.readFileSync(skillPath, 'utf8'),
        manifest: fs.readFileSync(manifestPath, 'utf8'),
        agents: fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'),
        state: JSON.parse(fs.readFileSync(statePath, 'utf8')) as Record<string, unknown>,
      };
      assert.equal(before.state.materializedAt, undefined, 'the fixture has never been stamped');

      const brokenRoot = fs.mkdtempSync(path.join(os.tmpdir(), 't1-converge-refusal-'));
      refusal.build(brokenRoot);
      const prevPlugin = process.env.TRAFFIC_ONE_PLUGIN_ROOT;
      process.env.TRAFFIC_ONE_PLUGIN_ROOT = brokenRoot;
      let out;
      try {
        out = materializeProjectFromState(dir, { trigger: 'unit' });
      } finally {
        if (prevPlugin === undefined) delete process.env.TRAFFIC_ONE_PLUGIN_ROOT; else process.env.TRAFFIC_ONE_PLUGIN_ROOT = prevPlugin;
        fs.rmSync(brokenRoot, { recursive: true, force: true });
      }

      assert.equal(out.status, 'skipped', refusal.name);
      assert.equal(out.result?.skipped, refusal.skipped, refusal.name);
      assert.equal(out.result?.removed, 0, `${refusal.name}: nothing deleted`);
      assert.equal(out.result?.written, 0, `${refusal.name}: nothing written`);
      // The diagnostic has to name the root, who supplied it, what is wrong, and
      // how to fix it — a bare "skipped" leaves the user with zero skills and no
      // idea why.
      assert.ok(out.context.includes(brokenRoot), `${refusal.name}: names the resolved root`);
      assert.ok(out.context.includes('TRAFFIC_ONE_PLUGIN_ROOT'), `${refusal.name}: names which env var supplied it`);
      assert.ok(out.context.includes('doctor'), `${refusal.name}: points at the doctor command`);
      assert.ok(out.context.includes('Nothing was deleted'), `${refusal.name}: states that disk is intact`);
      for (const needle of refusal.expect) {
        assert.ok(out.context.includes(needle), `${refusal.name}: explains the cause (${needle})`);
      }

      assert.equal(fs.readFileSync(rulePath, 'utf8'), before.rule, `${refusal.name}: rule is byte-identical`);
      assert.equal(fs.readFileSync(skillPath, 'utf8'), before.skill, `${refusal.name}: skill is byte-identical`);
      assert.equal(fs.readFileSync(manifestPath, 'utf8'), before.manifest, `${refusal.name}: manifest is byte-identical`);
      assert.equal(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'), before.agents, `${refusal.name}: AGENTS.md is byte-identical`);

      const after = JSON.parse(fs.readFileSync(statePath, 'utf8')) as Record<string, unknown>;
      assert.equal(after.materializedAt, undefined, `${refusal.name}: materializedAt is NOT stamped for a run that materialized nothing`);
      assert.equal(after.materializedVersion, before.state.materializedVersion, `${refusal.name}: materializedVersion is untouched`);
      assert.equal(after.materializedStack, before.state.materializedStack, `${refusal.name}: materializedStack is untouched`);
    });
  }
});

// THE SELF-HEAL. The refusal above protects a project that still has its content;
// this covers the projects that already lost it, before the refusal existed. Their
// manifest lists 1 skill, that 1 skill is on disk, the stamp is current, and
// isMaterialized() + hasMaterializedProjectAssets() therefore short-circuit every
// later convergence — so nothing looks wrong and the other 46 never come back.
test('materializeProjectIfNeeded: a project truncated by an earlier torn root re-converges and gets its content back', () => {
  withTempProject((dir) => withInstalledPluginRoot(() => {
    const statePath = writeCompleteMaterializedFixture(dir);
    const declared = declaredContent(dir);
    const t1 = path.join(dir, '.traffic-one');

    // Truncate exactly the way the bug did: one surviving skill, one surviving
    // rule, a manifest that agrees with disk, and a `materializedAt` stamp
    // claiming the run succeeded.
    const survivingRule = declared.rules[0];
    for (const relPath of declared.rules.slice(1)) fs.rmSync(path.join(t1, relPath), { force: true });
    for (const name of declared.skills.filter((s) => s !== 'project-memory')) {
      fs.rmSync(path.join(t1, 'skills', name), { recursive: true, force: true });
    }
    fs.writeFileSync(path.join(t1, 'manifest.json'), JSON.stringify({
      generatedBy: 'traffic-one', stack: 'default', rules: [survivingRule], skills: ['project-memory'],
    }), 'utf8');
    const stamped = JSON.parse(fs.readFileSync(statePath, 'utf8')) as Record<string, unknown>;
    stamped.materializedAt = '2026-01-01T00:00:00Z';
    writeState(dir, stamped);

    const out = materializeProjectIfNeeded(dir, { trigger: 'unit' });

    assert.ok(out, 'a truncated manifest must invoke the materializer instead of short-circuiting');
    assert.equal(out?.result?.skipped, undefined, `the healthy root must materialize, got ${out?.result?.skipped}`);
    const healed = JSON.parse(fs.readFileSync(path.join(t1, 'manifest.json'), 'utf8')) as Record<string, unknown>;
    assert.deepEqual([...(healed.skills as string[])].sort(), declared.skills, 'every declared skill is tracked again');
    for (const name of declared.skills) {
      assert.ok(fs.existsSync(path.join(t1, 'skills', name, 'SKILL.md')), `${name} is back on disk`);
    }
    for (const relPath of declared.rules) {
      assert.ok(fs.existsSync(path.join(t1, relPath)), `${relPath} is back on disk`);
    }

    // Self-limiting: the successful run rewrote the manifest, so the next hook
    // short-circuits again. A heal that re-fired every time would re-materialize
    // on every mutating tool call forever.
    assert.equal(materializeProjectIfNeeded(dir, { trigger: 'unit' }), null, 'the heal goes quiet once the project is whole');
  }));
});

// ── the refused STAMP ───────────────────────────────────────────────────────
// The refusals above are about the WRITER declining. These two are about the
// state write at the end, whose boolean was dropped: `materializedStack` /
// `materializedAt` / `materializedVersion` are the entire record that
// materialization happened, and `isMaterialized()` reads them to decide whether
// to converge again. Without them every later hook re-converges and keeps
// returning a NON-NULL outcome — which onboarding-gate/handler.ts reads on a
// mutating PreToolUse as allow+context after a successful heal, or
// `deny('materialization-not-converged')` when the stamp was refused. A refused
// stamp reported as `materialized` would now allow writes against an unstamped
// tree on every later hook. So the refused stamp must not report `materialized`.
//
// MOVE-ASIDE rather than a dangling link: writeState re-reads `.one.json` (for
// preserveCurrentRunId) and readEffectiveState reads it first, so a dangling link
// makes the read fail and the run bails before the write — a vacuous pass the
// writable baseline cannot catch, since the baseline is a different directory.
function fenceStateMoveAside(statePath: string): void {
  const aside = `${statePath}.aside`;
  const before = fs.readFileSync(statePath, 'utf8');
  fs.renameSync(statePath, aside);
  fs.symlinkSync(aside, statePath);
  assert.equal(fs.readFileSync(statePath, 'utf8'), before,
    'fixture guard: reads still resolve through the link, so the run reaches its write');
}

test('materializeProjectFromState: a refused materialization stamp is reported as failed, not materialized', () => {
  withTempProject((dir) => withInstalledPluginRoot(() => {
    const statePath = writeCompleteMaterializedFixture(dir);
    const baseline = materializeProjectFromState(dir, { trigger: 'unit' });
    assert.ok(baseline.status === 'materialized' || baseline.status === 'current',
      `writable baseline: an unfenced run materializes, got ${baseline.status}`);
    assert.equal(typeof JSON.parse(fs.readFileSync(statePath, 'utf8')).materializedAt, 'string',
      'writable baseline: and the stamp — the whole record that it happened — is on disk');
  }));

  withTempProject((dir) => withInstalledPluginRoot(() => {
    const statePath = writeCompleteMaterializedFixture(dir);
    fenceStateMoveAside(statePath);

    const out = materializeProjectFromState(dir, { trigger: 'unit' });
    assert.equal(out.status, 'failed',
      'a run whose stamp the fence refused must not report the project as materialized or current');
    assert.match(out.context, /\.one\.json/, 'and the diagnostic names the exact refused path');
    assert.match(out.context, /materializedStack/, 'and the fields that are missing because of it');
    assert.ok((out.result?.written ?? 0) > 0,
      'fixture guard: the assets really were written — this is the RECORD that is missing, not the content');
    assert.equal(JSON.parse(fs.readFileSync(statePath, 'utf8')).materializedAt, undefined,
      'fixture guard: the stamp really was refused');
  }));
});

test('materializeProjectIfNeeded: a refused canonicalization is not answered with "nothing needed"', () => {
  // The sharp shape: this state is materialized, its assets are complete, and the
  // three `return null` branches below the canonicalization would all say "nothing
  // needed" — about a project whose state file cannot be written at all.
  const seed = (dir: string): string => {
    const statePath = writeCompleteMaterializedFixture(dir);
    const state = JSON.parse(fs.readFileSync(statePath, 'utf8')) as Record<string, unknown>;
    state.materializedAt = '2026-01-01T00:00:00Z';
    state.materializedVersion = stateVersion();
    state.materializedStack = stackFingerprint(state);
    // Left noncanonical on purpose, so normalizeState reports a change and the
    // canonicalization write is actually attempted.
    delete state.confirmed;
    writeState(dir, state);
    return statePath;
  };

  withTempProject((dir) => withInstalledPluginRoot(() => {
    seed(dir);
    assert.equal(materializeProjectIfNeeded(dir, { trigger: 'unit' }), null,
      'writable baseline: an unfenced convergence on a whole, materialized project needs nothing');
  }));

  withTempProject((dir) => withInstalledPluginRoot(() => {
    const statePath = seed(dir);
    fenceStateMoveAside(statePath);

    const out = materializeProjectIfNeeded(dir, { trigger: 'unit' });
    assert.equal(out?.status, 'failed',
      'a project whose .one.json cannot be written is not "nothing needed"');
    assert.match(out?.context ?? '', /\.one\.json/, 'and the diagnostic names the exact refused path');
  }));
});

