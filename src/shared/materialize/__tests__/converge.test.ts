// An 'installed'-classified plugin root: the compiled runtime entry plus real
// content at the SHIPPED paths (`rules/**`, `skills-catalog/**`, `agents/**`).
// Any test that expects materialization to actually happen needs one, because
// materializeProjectAssets refuses every other layout — including this repo,
// which is a 'source' checkout under tsx and keeps its rules under
// `src/modules/rules/rules/**`, where no `<root>/rules/**` join can reach them.
function withInstalledPluginRoot(fn: () => void): void {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 't1-converge-plugin-'));
  const modules = path.resolve(__dirname, '..', '..', '..', 'modules');
  fs.mkdirSync(path.join(root, 'scripts'), { recursive: true });
  fs.writeFileSync(path.join(root, 'scripts', 'hook-runtime.cjs'), '// test fixture stub\n', 'utf8');
  // stateVersion() reads THIS root's package.json (pluginVersion, default
  // '0.0.0'), and it is what isMaterialized() compares materializedVersion
  // against — so a fixture root without one makes every version look stale-free.
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'traffic-one', version: '9.9.9' }), 'utf8');
  // Symlinks to the real trees, not a two-rule/two-skill stub: the writer now
  // refuses a root that resolves only PART of what the project's own runtime
  // declares (materialize.ts tornRootRefusal), and a stub is that shape.
  fs.symlinkSync(path.join(modules, 'rules', 'rules'), path.join(root, 'rules'), 'dir');
  fs.symlinkSync(path.join(modules, 'skills', 'skills-catalog'), path.join(root, 'skills-catalog'), 'dir');
  fs.mkdirSync(path.join(root, 'agents'), { recursive: true });
  for (const role of ['senior-frontend', 'senior-backend']) {
    fs.copyFileSync(path.join(modules, role, 'agent.md'), path.join(root, 'agents', `${role}.md`));
  }
  const previous = process.env.TRAFFIC_ONE_PLUGIN_ROOT;
  process.env.TRAFFIC_ONE_PLUGIN_ROOT = root;
  try {
    fn();
  } finally {
    if (previous === undefined) delete process.env.TRAFFIC_ONE_PLUGIN_ROOT; else process.env.TRAFFIC_ONE_PLUGIN_ROOT = previous;
    fs.rmSync(root, { recursive: true, force: true });
  }
}

