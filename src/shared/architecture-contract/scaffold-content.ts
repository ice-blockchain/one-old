// ── The compiled AST lint layer ─────────────────────────────────────────────
// Which real community linter owns hardcoded-copy detection for this profile.
// Where a layer exists, the write-time lexical i18n findings demote to
// warnings (the AST rule sees copy in EVERY syntactic position — ternaries,
// `&&` branches, `.map()` callbacks — exactly where the lexical scanner
// provably missed a shipped bug in 13co). Profiles that return null KEEP the
// blocking lexical scanner: no mature AST equivalent exists for them
// (Svelte and Astro have no maintained no-raw-text plugin as of 2026-07).
export type UiAstLintLayer = 'react-i18next' | 'vue-i18n';

export function uiAstLintLayer(
  profile: CapabilityProfileV1 | undefined,
): UiAstLintLayer | null {
  if (!profile) return null;
  if (profileUsesReactI18n(profile)) return 'react-i18next';
  if (profile.profileId === 'vue' || profile.profileId === 'nuxt') return 'vue-i18n';
  return null;
}

