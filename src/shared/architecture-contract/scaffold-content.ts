// `.env.example` goes to `senior-backend` whenever that role exists, so an
// UNCONDITIONAL Vite body seeded `VITE_SITE_URL=` into API-only projects that
// will never have a sitemap — observed in 15cl, where the Go backend replaced it
// by hand. The crawl-origin language is real compiled knowledge tied to
// sitemap/canonical generation; it belongs only on a profile that has that
// surface.
/**
 * The public site-url variable a given web framework actually reads.
 *
 * Shared with `run-bootstrap-policy/integration-requirements.ts`, which resolves
 * the same name from compiled output paths and puts it in the implementer's
 * integration requirements. Seeding a different variable than the requirement
 * names means the role is told to read `NEXT_PUBLIC_SITE_URL` from a file that
 * documents `VITE_SITE_URL` — the value is empty either way, so nothing fails
 * loudly; the role just cannot find the contract it was pointed at.
 */
export function siteUrlEnvVarForFramework(framework: string | undefined): string {
  switch ((framework || '').toLowerCase()) {
    case 'nextjs': return 'NEXT_PUBLIC_SITE_URL';
    case 'nuxt': return 'NUXT_PUBLIC_SITE_URL';
    case 'svelte':
    case 'sveltekit': return 'PUBLIC_SITE_URL';
    case 'laravel': return 'APP_URL';
    case 'angular': return 'SITE_URL';
    default: return 'VITE_SITE_URL';
  }
}

