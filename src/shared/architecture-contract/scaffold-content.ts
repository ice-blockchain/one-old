// src/shared/architecture-contract/scaffold-content.ts
// Canonical bodies for scaffold files whose CONTENT is runtime knowledge, not
// a design decision.
//
// The compiler only ever emitted scaffold PATHS; the required `.prettierignore`
// entries lived exclusively in rules prose, so a run shipped the file empty
// and the implementer burned four turns discovering `.traffic-one`,
// `pnpm-lock.yaml`, and `.turbo` serially through formatter failures
// (observed 8co). Same story for `.env.example`: the crawl-origin gate names
// `VITE_SITE_URL` but nothing ever wrote the variable anywhere an agent could
// legally source it from.
//
// Deterministic and idempotent: content is seeded ONLY when the file is
// missing or blank; a non-empty agent-authored file is never overwritten.

