function renderRuleIndexSection(title, relPaths) {
  if (!Array.isArray(relPaths) || relPaths.length === 0) return [];
  return [
    `### ${title}`,
    '',
    ...relPaths.map((relPath) => `- .traffic-one/${relPath}`),
    '',
  ];
}

function ruleGroupsForOptions(rules, options) {
  const mandatory = unique(options.mandatoryRules || []);
  const reference = unique(options.referenceRules || [])
    .filter((relPath) => !mandatory.includes(relPath));
  if (mandatory.length > 0 || reference.length > 0) {
    return { mandatory, reference };
  }
  return { mandatory: unique(rules), reference: [] };
}

function renderAgents(state, rules, skills, options = {}) {
  const leanMode = options.leanMode === true;
  const lines = [
    '# Traffic One Local Agent Context',
    '',
    GENERATED_MARKER,
    '',
    leanMode
      ? 'Use the compact project-local rule kernel and index below before falling back to plugin-root rules.'
      : 'Use the project-local active rule bundle below before falling back to plugin-root rules.',
    leanMode
      ? 'Compact context mode keeps critical guidance always-on and reads full `.traffic-one` rules on demand.'
      : 'Host runtimes may read AGENTS.md directly, so active rule contents are inlined instead of relying on host-specific import syntax.',
    '',
    '## Active State',
    '',
    `- Stack: ${state.stack || 'minimal'}`,
    `- Frontend: ${state.frontend || 'none'}`,
    `- Backend: ${state.backend || 'none'}`,
    `- Mobile: ${(state.mobile && state.mobile.framework) || 'none'}`,
    '',
    '## Active Rules',
    '',
    ...rules.map((relPath) => `- .traffic-one/${relPath}`),
    '',
    '## Active Skills',
    '',
    ...skills.map((name) => `- .traffic-one/skills/${name}/SKILL.md`),
    '',
  ];
  if (leanMode) {
    const { mandatory, reference } = ruleGroupsForOptions(rules, options);
    lines.push(
      ...compactRuleKernel(),
      ...compactReadRouting(),
      '## Active Rule Index',
      '',
      'Full rule content is materialized under `.traffic-one/<path>`.',
      'Read only the specific rules needed for the current file or task; the kernel above is the always-on baseline.',
      '',
      ...renderRuleIndexSection('Mandatory Baseline', mandatory),
      ...renderRuleIndexSection('Reference On Demand', reference),
    );
    return `${lines.join('\n')}\n`;
  }

  const root = pluginRoot();
  lines.push('## Active Rule Contents', '');
  for (const relPath of rules) {
    const source = readText(path.join(root, templatePath(relPath)));
    lines.push(`### ${relPath}`, '');
    if (typeof source === 'string' && source.trim()) {
      lines.push(source.trimEnd(), '');
    } else {
      lines.push(`Rule source missing in plugin root: ${templatePath(relPath)}`, '');
    }
  }
  return `${lines.join('\n')}\n`;
}

function localContextName(fileName) {
  return fileName === 'CLAUDE.md' ? 'CLAUDE.local.md' : 'AGENTS.local.md';
}

function preserveManualRootContext(cwd, fileName, state) {
  const rootPath = path.join(cwd, fileName);
  if (!fs.existsSync(rootPath)) return false;
  const stat = fs.lstatSync(rootPath);
  if (stat.isSymbolicLink() || isGenerated(rootPath)) return false;
  if (!state || state.mode !== 'new-project') return false;

  const localName = localContextName(fileName);
  const localPath = path.join(cwd, '.traffic-one', localName);
  const existing = readText(rootPath) || '';
  const preserved = [
    `# Preserved ${fileName}`,
    '',
    `This content existed before Traffic One generated root ${fileName}.`,
    '',
    '---',
    '',
    existing.trimEnd(),
    '',
  ].join('\n');

  if (!fs.existsSync(localPath)) {
    writeTextIfChanged(localPath, preserved);
  }
  fs.rmSync(rootPath, { force: true });
  return true;
}

function localContextBlocks(cwd) {
  const blocks = [];
  for (const fileName of ['AGENTS.local.md', 'CLAUDE.local.md']) {
    const filePath = path.join(cwd, '.traffic-one', fileName);
    const content = readText(filePath);
    if (typeof content === 'string' && content.trim()) {
      blocks.push(`### .traffic-one/${fileName}\n\n${content.trimEnd()}`);
    }
  }
  return blocks;
}

function renderAgentsWithLocalContext(cwd, state, rules, skills, options = {}) {
  const base = renderAgents(state, rules, skills, {
    leanMode: isLeanMaterialization(cwd, state),
    ...options,
  }).trimEnd();
  const localBlocks = localContextBlocks(cwd);
  if (localBlocks.length === 0) {
    return `${base}\n`;
  }
  return [
    base,
    '',
    '## Preserved Project Notes',
    '',
    ...localBlocks,
    '',
  ].join('\n');
}

function renderClaudeFallback() {
  const lines = [
    '# Traffic One Claude Context',
    '',
    GENERATED_MARKER,
    '',
    'Read the canonical root agent context:',
    '',
    '@AGENTS.md',
    '',
  ];
  return `${lines.join('\n')}\n`;
}

function writeRootAgents(cwd, content) {
  const rootAgents = path.join(cwd, 'AGENTS.md');
  if (fs.existsSync(rootAgents) && !fs.lstatSync(rootAgents).isSymbolicLink() && !isGenerated(rootAgents)) {
    return false;
  }
  if (fs.existsSync(rootAgents)) {
    fs.rmSync(rootAgents, { force: true });
  }
  return writeTextIfChanged(rootAgents, content);
}

function writeRootClaude(cwd) {
  const rootClaude = path.join(cwd, 'CLAUDE.md');
  if (fs.existsSync(rootClaude) && !fs.lstatSync(rootClaude).isSymbolicLink() && !isGenerated(rootClaude)) {
    return false;
  }
  if (fs.existsSync(rootClaude)) {
    fs.rmSync(rootClaude, { force: true });
  }
  try {
    fs.symlinkSync('AGENTS.md', rootClaude);
    return true;
  } catch {
    return writeTextIfChanged(rootClaude, renderClaudeFallback());
  }
}

function unique(values) {
  const seen = new Set();
  const out = [];
  for (const value of values) {
    if (!value || seen.has(value)) continue;
    seen.add(value);
    out.push(value);
  }
  return out;
}

function modeRulesForState(root, state) {
  const mode = state && typeof state.mode === 'string' ? state.mode : '';
  if (!mode) return [];

  const relPath = `rules/modes/${mode}.md`;
  if (!fs.existsSync(path.join(root, templatePath(relPath)))) return [];

  return [relPath];
}

function materializeProjectAssets(cwd, state) {
  if (isPluginAuthoringRoot(cwd)) {
    return {
      rules: 0,
      skills: 0,
      written: 0,
      removed: 0,
      contextProfile: 'plugin-authoring',
      skipped: 'plugin-authoring-root',
    };
  }

  const root = pluginRoot();
  const leanMode = isLeanMaterialization(cwd, state);
  const spec = stackSpecForState(state);
  const mandatoryRules = unique([
    ...spec.mandatory,
    ...modeRulesForState(root, state),
  ]).filter((relPath) => fs.existsSync(path.join(root, templatePath(relPath))));
  const referenceRules = unique(spec.optional)
    .filter((relPath) => fs.existsSync(path.join(root, templatePath(relPath))));
  const rules = unique([
    ...mandatoryRules,
    ...referenceRules,
  ]);
  const skills = [...activeSkillsFor(state)].filter((name) => fs.existsSync(path.join(root, 'skills-templates', name, 'SKILL.md'))).sort();
  const nextRulePaths = new Set(rules);
  const nextSkillNames = new Set(skills);
  const previous = loadPreviousManifest(cwd);
  const removed = cleanupPrevious(cwd, previous, nextRulePaths, nextSkillNames);

  let written = 0;
  const projectMemoryRoot = path.join(cwd, '.traffic-one');
  for (const relPath of rules) {
    const src = path.join(root, templatePath(relPath));
    const dst = path.join(projectMemoryRoot, relPath);
    const source = fs.readFileSync(src, 'utf8').trimEnd();
    const content = `${GENERATED_MARKER}\n<!-- SOURCE: ${templatePath(relPath)} -->\n\n${source}\n`;
    if (writeTextIfChanged(dst, content)) written += 1;
  }

  const skillsRoot = path.join(cwd, '.traffic-one', 'skills');
  for (const name of skills) {
    if (copySkillDir(path.join(root, 'skills-templates', name), path.join(skillsRoot, name))) {
      written += 1;
    }
  }

  if (preserveManualRootContext(cwd, 'AGENTS.md', state)) written += 1;
  if (preserveManualRootContext(cwd, 'CLAUDE.md', state)) written += 1;

  const localAgents = renderAgentsWithLocalContext(cwd, state, rules, skills, {
    mandatoryRules,
    referenceRules,
  });
  if (writeRootAgents(cwd, localAgents)) written += 1;
  if (writeRootClaude(cwd)) written += 1;

  const manifest = {
    generatedBy: 'traffic-one',
    generatedAt: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
    contextProfile: leanMode ? 'lean' : 'full',
    stack: state.stack || 'minimal',
    frontend: state.frontend || 'none',
    backend: state.backend || 'none',
    mobile: (state.mobile && state.mobile.framework) || 'none',
    rules: rules.map(toPosix),
    skills,
  };
  if (writeTextIfChanged(
    path.join(cwd, '.traffic-one', 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  )) {
    written += 1;
  }

  return { rules: rules.length, skills: skills.length, written, removed, contextProfile: leanMode ? 'lean' : 'full' };
}

function hasMaterializedProjectAssets(cwd, state) {
  const manifestPath = path.join(cwd, '.traffic-one', 'manifest.json');
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  } catch {
    return false;
  }

  if (!manifest || manifest.generatedBy !== 'traffic-one') return false;
  if (state && manifest.stack && state.stack && manifest.stack !== state.stack) return false;
  if (!Array.isArray(manifest.rules) || manifest.rules.length === 0) return false;
  if (!Array.isArray(manifest.skills) || manifest.skills.length === 0) return false;

  const agentsPath = path.join(cwd, 'AGENTS.md');
  if (!fs.existsSync(agentsPath) || !isGenerated(agentsPath)) return false;
  if (!fs.existsSync(path.join(cwd, 'CLAUDE.md'))) return false;

  for (const relPath of manifest.rules) {
    if (!fs.existsSync(path.join(cwd, '.traffic-one', relPath))) return false;
  }
  for (const name of manifest.skills) {
    if (!fs.existsSync(path.join(cwd, '.traffic-one', 'skills', name, 'SKILL.md'))) {
      return false;
    }
  }
  return true;
}

// ── Graph preview ─────────────────────────────────────────────────────────────
// Compact (~500 token) summary of the codebase graph that subagents see in
// their SessionStart bundle. They scope file reads from this list instead of
// having to do a full Read of the graph artefact first.
const GRAPH_PREVIEW_MAX_BYTES = 2048;
const GRAPH_PREVIEW_MAX_MODULES = 30;

function generateGraphPreview(cwd, provider) {
  const lines = ['## Codebase graph preview', ''];
  if (provider === 'graphify') {
    const reportPath = path.join(cwd, 'graphify-out', 'GRAPH_REPORT.md');
    if (!fs.existsSync(reportPath)) return null;
    let text;
    try { text = fs.readFileSync(reportPath, 'utf8'); } catch { return null; }
    const modules = [];
    const headingRe = /^##\s+(.+?)\s*$/gm;
    let m;
    while ((m = headingRe.exec(text)) !== null) modules.push(m[1]);
    lines.push(`Provider: graphify · ${modules.length} top-level section(s):`);
    for (const name of modules.slice(0, GRAPH_PREVIEW_MAX_MODULES)) lines.push(`- ${name}`);
    if (modules.length > GRAPH_PREVIEW_MAX_MODULES) {
      lines.push(`- … +${modules.length - GRAPH_PREVIEW_MAX_MODULES} more`);
    }
    lines.push('');
    lines.push('Read `graphify-out/GRAPH_REPORT.md` for module-specific scoping.');
  } else if (provider === 'gitnexus') {
    const gnDir = path.join(cwd, '.gitnexus');
    if (!fs.existsSync(gnDir)) return null;
    const indexPath = path.join(gnDir, 'index.json');
    let listed = false;
    if (fs.existsSync(indexPath)) {
      try {
        const idx = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
        const modules = Array.isArray(idx.modules)
          ? idx.modules.slice(0, GRAPH_PREVIEW_MAX_MODULES)
          : [];
        if (modules.length > 0) {
          lines.push(`Provider: gitnexus · ${modules.length} top-level module(s):`);
          for (const mod of modules) lines.push(`- ${mod.name || mod.path || String(mod)}`);
          listed = true;
        }
      } catch {
        // fall through to non-listed branch
      }
    }
    if (!listed) {
      lines.push(`Provider: gitnexus · graph available at \`.gitnexus/\``);
    }
    lines.push('');
    lines.push('Read `.gitnexus/` artefacts for module-specific scoping.');
  } else {
    return null;
  }
  let body = lines.join('\n') + '\n';
  if (body.length > GRAPH_PREVIEW_MAX_BYTES) {
    body = body.slice(0, GRAPH_PREVIEW_MAX_BYTES - 80)
      + '\n…[truncated; read the full graph artefact for the complete listing]\n';
  }
  return body;
}

// Idempotent: writes .traffic-one/graph-preview.md when the graph artefact
// exists. Returns true on successful write, false when no graph or write fails.
function writeGraphPreview(cwd, provider) {
  const body = generateGraphPreview(cwd, provider);
  if (!body) return false;
  const dst = path.join(cwd, '.traffic-one', 'graph-preview.md');
  try {
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.writeFileSync(dst, body, 'utf8');
    return true;
  } catch {
    return false;
  }
}

